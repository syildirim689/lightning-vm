  const { db, call } = pool();
  await h.task(call, { task: (await h.clone(call, order)).task });
  const [, vm] = made(db); const vdis = vm.VBDs.map((b) => db.VBD[b].VDI);
  await assert.rejects(h.destroy(call, { vm: uuid(12) }), { code: 'NOT_MANAGED' });
