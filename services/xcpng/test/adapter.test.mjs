test('resize, extra disks and snapshots', async () => {
  const { db, call } = pool();
  await h.task(call, { task: (await h.clone(call, order)).task });
  const [, vm] = made(db);
  await h.resize(call, { vm: vm.uuid, vcpu: 2, memoryMb: 2048, diskGb: 60 });
  assert.deepEqual([vm.VCPUs_max, vm.VCPUs_at_startup, vm.memory_static_max], [2, 2, 2048 * MIB], 'lowering goes start-up first, raising maximum first');
  await assert.rejects(h.resize(call, { vm: vm.uuid, vcpu: 2, memoryMb: 2048, diskGb: 10 }), { code: 'DISK_SHRINK_NOT_SUPPORTED' });
  await h.diskAdd(call, { vm: vm.uuid, sizeGb: 20 });
  assert.deepEqual((await h.disks(call, { vm: vm.uuid })).disks.map((d) => [d.key, d.sizeGb, d.system]), [[0, 60, true], [1, 20, false]]);
  await assert.rejects(h.diskRemove(call, { vm: vm.uuid, key: 0 }), { code: 'SYSTEM_DISK' });
  assert.deepEqual(await h.diskRemove(call, { vm: vm.uuid, key: 1 }), { task: '' });
  assert.deepEqual(await h.diskRemove(call, { vm: vm.uuid, key: 1 }), { task: '', gone: true });
  await h.snapshot(call, { vm: vm.uuid, action: 'create', name: 'before the upgrade', description: 'ticket 42' });
  const [s] = (await h.snapshots(call, { vm: vm.uuid })).snapshots;
  assert.match(s.id, /^snapshot-\d{1,12}$/); assert.deepEqual([s.name, s.description, s.created], ['before the upgrade', 'ticket 42', '2024-01-01T10:00:00.000Z']);
  await assert.rejects(h.resize(call, { vm: vm.uuid, vcpu: 2, memoryMb: 2048, diskGb: 80 }), { code: 'DISK_HAS_SNAPSHOTS' });
  await assert.rejects(h.snapshot(call, { vm: vm.uuid, action: 'revert', snapshot: 'snapshot-1' }), { code: 'SNAPSHOT_NOT_FOUND' });
  assert.deepEqual(await h.snapshot(call, { vm: vm.uuid, action: 'revert', snapshot: s.id }), { task: '' });
  await h.snapshot(call, { vm: vm.uuid, action: 'remove', snapshot: s.id });
  assert.deepEqual((await h.snapshots(call, { vm: vm.uuid })).snapshots, []);
});

